const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const Module = require("node:module");
const root = path.resolve(__dirname, "../..");
const dependencies = path.join(root, ".work/upgrade2-u2-07/dependencies/node_modules");
const React = require(path.join(dependencies, "react"));
const {renderToStaticMarkup} = require(path.join(dependencies, "react-dom/server"));
const {Window} = require(path.join(dependencies, "happy-dom/cjs/index.cjs"));
const {buildSync} = require(path.join(dependencies, "esbuild"));
const {cases,catalog} = JSON.parse(fs.readFileSync(0, "utf8"));
const output = buildSync({entryPoints:[path.join(root,"app/webui/Upgrade2RunPanel.tsx"),path.join(root,"app/webui/Upgrade2MethodSelection.tsx")],bundle:true,write:false,outdir:path.join(root,"app/tests/method-ui-build"),platform:"node",format:"cjs",jsx:"automatic",nodePaths:[dependencies],external:["react","react/jsx-runtime"],loader:{".css":"empty"}});
const moduleView = new Module(path.join(root,"app/tests/u2_09_method_bundle.cjs"));
moduleView.filename = path.join(root,"app/tests/u2_09_method_bundle.cjs");
moduleView.paths = [dependencies];
moduleView._compile(output.outputFiles.find(item=>item.path.endsWith("/Upgrade2RunPanel.js")).text,moduleView.filename);
const {Upgrade2RunPanel} = moduleView.exports;
const window = new Window();
for(const item of cases){
  const run={run_id:item.run.run_id,goal:item.run.goal,revision:item.run.revision,goal_revision:item.run.goal_revision,status:item.run.status,allowed_actions:[],waiting_inputs:[],intent:null,artifacts:[]};
  const render=(connection,error=null)=>new window.DOMParser().parseFromString(renderToStaticMarkup(React.createElement(Upgrade2RunPanel,{run,events:item.events,event_base_seq:0,connection,loading:false,busy:false,error,supplement:""})),"text/html");
  const text=render("CONNECTED").body.textContent, method=item.method.payload.method_ref;
  assert.ok(text.includes(method.sop_id));
  assert.ok(text.includes(method.version));
  assert.ok(text.includes(method.content_sha256));
  assert.ok(text.includes("模型实际采用尚未核查"));
  assert.ok(text.includes(item.run.goal_revision===item.method.payload.goal_revision?"当前目标版本":"历史目标版本"));
  assert.ok(!render("DISCONNECTED").body.textContent.includes(method.content_sha256));
  assert.ok(!render("CONNECTED","读取失败").body.textContent.includes(method.content_sha256));
}
const selectionModule=new Module(path.join(root,"app/tests/u2_09_method_selection_bundle.cjs"));
selectionModule.filename=path.join(root,"app/tests/u2_09_method_selection_bundle.cjs");
selectionModule.paths=[dependencies];
selectionModule._compile(output.outputFiles.find(item=>item.path.endsWith("/Upgrade2MethodSelection.js")).text,selectionModule.filename);
const {Upgrade2MethodSelection}=selectionModule.exports;
const unavailable=new window.DOMParser().parseFromString(renderToStaticMarkup(React.createElement(Upgrade2MethodSelection,{allowed:false,catalog,onSelect:()=>{}})),"text/html");
assert.ok(unavailable.body.textContent.includes("尚未允许"));
assert.ok(Array.from(unavailable.querySelectorAll("select,button")).every(element=>element.disabled));
for(const item of catalog.methods){assert.ok(unavailable.body.textContent.includes(item.name));if(item.status==="UNAVAILABLE")assert.ok(unavailable.body.textContent.includes(item.reasons[0]));}
global.window=window;global.document=window.document;global.navigator=window.navigator;global.IS_REACT_ACT_ENVIRONMENT=true;
const {createRoot}=require(path.join(dependencies,"react-dom/client"));
const container=document.createElement("div");document.body.appendChild(container);const view=createRoot(container);
React.act(()=>view.render(React.createElement(Upgrade2MethodSelection,{allowed:false,catalog,onSelect:()=>{}})));
assert.ok(container.textContent.includes(catalog.methods[0].name));
React.act(()=>view.render(React.createElement(Upgrade2MethodSelection,{allowed:false,catalog:null,onSelect:()=>{}})));
assert.ok(!container.textContent.includes(catalog.methods[0].name));
assert.ok(container.textContent.includes("尚未取得当前运行的方法目录"));
React.act(()=>view.unmount());
process.stdout.write(JSON.stringify({checked:cases.length}));
