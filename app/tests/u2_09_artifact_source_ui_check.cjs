const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const Module = require("node:module");
const root = path.resolve(__dirname, "../..");
const dependencies = path.join(root, ".work/upgrade2-u2-07/dependencies/node_modules");
const {buildSync} = require(path.join(dependencies, "esbuild"));
const React = require(path.join(dependencies, "react"));
const {renderToStaticMarkup} = require(path.join(dependencies, "react-dom/server"));
const ref = JSON.parse(fs.readFileSync(0, "utf8"));
const output = buildSync({entryPoints:[path.join(root,"app/webui/Upgrade2ArtifactList.tsx")],bundle:true,write:false,platform:"node",format:"cjs",jsx:"automatic",nodePaths:[dependencies],external:["react","react/jsx-runtime"]});
const bundle = new Module(path.join(root,"app/tests/u2_09_artifact_source_bundle.cjs"));
bundle.filename = path.join(root,"app/tests/u2_09_artifact_source_bundle.cjs");
bundle.paths = [dependencies];
bundle._compile(output.outputFiles[0].text,bundle.filename);
const {ArtifactSourceReference,artifactListError} = bundle.exports;
assert.equal(typeof ArtifactSourceReference,"function");
const html=renderToStaticMarkup(React.createElement(ArtifactSourceReference,{source:ref,onOpenSource:()=>{},onOpenHistory:()=>{}}));
for(const value of [ref.source_id,ref.revision,ref.locator,ref.sha256,ref.classification])assert.ok(html.includes(value));
assert.ok(html.includes("原文位置未经核查"));
assert.ok(html.includes("查看引用版本"));
for(const status of [401,403,404,409,410])assert.ok(artifactListError(status).includes("不可读取"));
assert.ok(artifactListError(503).includes("尚不可用"));
process.stdout.write(JSON.stringify({reference_visible:true}));
