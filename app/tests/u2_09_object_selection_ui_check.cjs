const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const Module = require("node:module");
const root = path.resolve(__dirname, "../..");
const dependencies = path.join(root, ".work/upgrade2-u2-07/dependencies/node_modules");
const React = require(path.join(dependencies, "react"));
const {renderToStaticMarkup} = require(path.join(dependencies, "react-dom/server"));
const {Window} = require(path.join(dependencies, "happy-dom/cjs/index.cjs"));
const {buildSync} = require(path.join(dependencies, "esbuild"));
const {catalog,unavailable} = JSON.parse(fs.readFileSync(0, "utf8"));
const result = buildSync({entryPoints:[path.join(root,"app/webui/Upgrade2ObjectSelection.tsx")],bundle:true,write:false,platform:"node",format:"cjs",jsx:"automatic",nodePaths:[dependencies],external:["react","react/jsx-runtime"]});
const component = new Module(path.join(root,"app/tests/object-selection-bundle.cjs"));
component.filename = path.join(root,"app/tests/object-selection-bundle.cjs");
component.paths = [dependencies];
component._compile(result.outputFiles[0].text,component.filename);
const {ObjectChoices,ObjectSelectionAvailability} = component.exports;
const window = new Window();
const render = (selected,canSelect) => new window.DOMParser().parseFromString(renderToStaticMarkup(React.createElement(ObjectChoices,{catalog,selected,canSelect,onChange:()=>{},onSubmit:()=>{}})),"text/html");
const initial = render([],true);
assert.equal(initial.querySelectorAll("input:checked").length,0);
assert.equal(initial.querySelector("button").disabled,true);
for(const item of catalog.objects){
  assert.ok(initial.body.textContent.includes(item.object_id));
  assert.ok(initial.body.textContent.includes(item.version));
  assert.ok(initial.body.textContent.includes(item.sha256));
  for(const source of item.source_refs)assert.ok(initial.body.textContent.includes(source.source_id));
}
const first=catalog.objects[0];
const selected=render([JSON.stringify([first.entity_type,first.object_id])],true);
assert.equal(selected.querySelectorAll("input:checked").length,1);
assert.equal(selected.querySelector("button").disabled,false);
const disabled=render([JSON.stringify([first.entity_type,first.object_id])],false);
assert.ok(Array.from(disabled.querySelectorAll("input,button")).every(item=>item.disabled));
const denied = new window.DOMParser().parseFromString(renderToStaticMarkup(React.createElement(ObjectChoices,{catalog:unavailable,selected:[JSON.stringify([first.entity_type,first.object_id])],canSelect:true,onChange:()=>{},onSubmit:()=>{}})),"text/html");
assert.ok(Array.from(denied.querySelectorAll("input,button")).every(item=>item.disabled));
const explanation=renderToStaticMarkup(React.createElement(ObjectSelectionAvailability,{catalog:unavailable}));
for(const reason of unavailable.unavailable_reasons)assert.ok(explanation.includes(reason));
assert.ok(explanation.includes("当前运行状态不允许新增对象选择"));
global.window=window;global.document=window.document;global.navigator=window.navigator;global.IS_REACT_ACT_ENVIRONMENT=true;
const {createRoot}=require(path.join(dependencies,"react-dom/client"));
const container=window.document.createElement("div");
window.document.body.appendChild(container);
const view=createRoot(container);
const submissions=[];
function Selection(){
  const [keys,setKeys]=React.useState([]);
  return React.createElement(ObjectChoices,{catalog,selected:keys,canSelect:true,onChange:setKeys,onSubmit:event=>{event.preventDefault();submissions.push(keys);}});
}
React.act(()=>view.render(React.createElement(Selection)));
assert.equal(container.querySelector("button").disabled,true);
React.act(()=>container.querySelector("input").click());
assert.equal(container.querySelector("button").disabled,false);
React.act(()=>container.querySelector("button").click());
assert.deepEqual(submissions,[[JSON.stringify([first.entity_type,first.object_id])]]);
React.act(()=>container.querySelector("input").click());
assert.equal(container.querySelector("button").disabled,true);
React.act(()=>view.unmount());
process.stdout.write(JSON.stringify({objects:catalog.objects.length}));
