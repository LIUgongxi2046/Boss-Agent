const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const Module = require("node:module");
const root = path.resolve(__dirname, "../..");
const dependencies = path.join(root, ".work/upgrade2-u2-07/dependencies/node_modules");
const {buildSync} = require(path.join(dependencies, "esbuild"));
const React = require(path.join(dependencies, "react"));
const {renderToStaticMarkup} = require(path.join(dependencies, "react-dom/server"));
const data = JSON.parse(fs.readFileSync(0, "utf8"));
const output = buildSync({entryPoints:[path.join(root,"app/webui/Upgrade2SourceHistory.tsx")],bundle:true,write:false,platform:"node",format:"cjs",jsx:"automatic",nodePaths:[dependencies],external:["react","react/jsx-runtime"]});
const moduleView = new Module(path.join(root,"app/tests/u2_09_source_history_bundle.cjs"));
moduleView.filename = path.join(root,"app/tests/u2_09_source_history_bundle.cjs");
moduleView.paths = [dependencies];
moduleView._compile(output.outputFiles[0].text,moduleView.filename);
const {validateHistory,historyError,HistoryContent,Upgrade2SourceHistory} = moduleView.exports;
const checked = validateHistory(data.history,data.reference);
const html = renderToStaticMarkup(React.createElement(HistoryContent,{data:checked}));
assert.ok(html.includes(data.history.content));
assert.ok(html.includes("引用版本 "+data.reference.version));
assert.ok(html.includes("当前版本 "+data.history.current_version));
assert.ok(html.includes("历史版本"));
const initial = renderToStaticMarkup(React.createElement(Upgrade2SourceHistory,{reference:data.reference,token:"",getToken:()=>"",onClose:()=>{}}));
assert.ok(initial.includes(data.reference.locator));
assert.ok(initial.includes("原文位置未经核查"));
assert.throws(()=>validateHistory(data.history,{...data.reference,version:data.history.current_version}),/不一致/);
assert.throws(()=>validateHistory(data.history,{...data.reference,sha256:"0".repeat(64)}),/不一致/);
assert.throws(()=>validateHistory(data.history,{...data.reference,locator:"未记录的位置"}),/不一致/);
for(const status of [401,403,404,409,410])assert.ok(historyError(status).includes("不可读取"));
process.stdout.write(JSON.stringify({historical:checked.historical,locator_verification:checked.citations[0].locator_verification}));
