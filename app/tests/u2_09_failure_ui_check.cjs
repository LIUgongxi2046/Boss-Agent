const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const Module = require("node:module");
const root = path.resolve(__dirname, "../..");
const dependencies = path.join(root,".work/upgrade2-u2-07/dependencies/node_modules");
const React = require(path.join(dependencies,"react"));
const {renderToStaticMarkup} = require(path.join(dependencies,"react-dom/server"));
const {buildSync} = require(path.join(dependencies,"esbuild"));
const data = JSON.parse(fs.readFileSync(0,"utf8"));
const output = buildSync({entryPoints:[path.join(root,"app/webui/Upgrade2RunPanel.tsx")],bundle:true,write:false,platform:"node",format:"cjs",jsx:"automatic",nodePaths:[dependencies],external:["react","react/jsx-runtime"],loader:{".css":"empty"}});
const bundle = new Module(path.join(root,"app/tests/u2_09_failure_bundle.cjs"));
bundle.filename = path.join(root,"app/tests/u2_09_failure_bundle.cjs");
bundle.paths = [dependencies];
bundle._compile(output.outputFiles[0].text,bundle.filename);
const run = {run_id:data.run_id,goal:"",revision:data.revision,goal_revision:1,status:data.status,allowed_actions:[],waiting_inputs:[],intent:null,artifacts:[]};
const render = (connection,error=null)=>renderToStaticMarkup(React.createElement(bundle.exports.Upgrade2RunPanel,{run,events:data.events,event_base_seq:0,connection,loading:false,busy:false,error,supplement:""}));
assert.ok(render("CONNECTED").includes(data.failure.payload.error_code));
assert.ok(!render("DISCONNECTED").includes(data.failure.payload.error_code));
assert.ok(!render("CONNECTED","读取失败").includes(data.failure.payload.error_code));
process.stdout.write(JSON.stringify({failure_visible:true,error_code:data.failure.payload.error_code}));
