const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const Module = require("node:module");
const root = path.resolve(__dirname,"../..");
const dependencies = path.join(root,".work/upgrade2-u2-07/dependencies/node_modules");
const React = require(path.join(dependencies,"react"));
const {renderToStaticMarkup} = require(path.join(dependencies,"react-dom/server"));
const {buildSync} = require(path.join(dependencies,"esbuild"));
const input = JSON.parse(fs.readFileSync(0,"utf8"));
const output = buildSync({entryPoints:[path.join(root,"app/webui/MemoryContentGate.tsx")],bundle:true,write:false,platform:"node",format:"cjs",jsx:"automatic",nodePaths:[dependencies],external:["react","react/jsx-runtime"]});
const bundle = new Module(path.join(root,"app/tests/u2_05_memory_gate_bundle.cjs"));
bundle.filename = path.join(root,"app/tests/u2_05_memory_gate_bundle.cjs");
bundle.paths = [dependencies];
bundle._compile(output.outputFiles[0].text,bundle.filename);
const base = {loading:false,busy:false,pending:false,error:"",ready:true};
const render = props=>renderToStaticMarkup(React.createElement(bundle.exports.MemoryContentGate,props,React.createElement("p",null,input.before.current.text)));
assert.ok(render(base).includes(input.before.current.text));
for(const patch of [{loading:true},{busy:true},{pending:true},{error:"读取失败"},{ready:false}])assert.ok(!render({...base,...patch}).includes(input.before.current.text));
assert.equal(input.after.current,null);
process.stdout.write(JSON.stringify({stale_hidden:true}));
