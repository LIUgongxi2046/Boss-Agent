const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const Module = require("node:module");
const root = path.resolve(__dirname, "../..");
const dependencies = path.join(root, ".work/upgrade2-u2-07/dependencies/node_modules");
const {buildSync} = require(path.join(dependencies, "esbuild"));
const built = buildSync({entryPoints: [path.join(root, "app/webui/Upgrade2CompletionInspection.tsx"), path.join(root, "app/webui/upgrade2-run-client.ts")], bundle: true,
  write: false, outdir: path.join(root, "app/tests/completion-logic-build"), platform: "node", format: "cjs",
  jsx: "automatic", nodePaths: [dependencies], external: ["react", "react/jsx-runtime"], loader: {".css": "empty"}});
const compiled = new Module(path.join(root, "app/tests/Upgrade2CompletionInspection.cjs"));
compiled.filename = path.join(root, "app/tests/Upgrade2CompletionInspection.cjs");
compiled.paths = [dependencies];
compiled._compile(built.outputFiles.find(item => item.path.endsWith("/Upgrade2CompletionInspection.js")).text, compiled.filename);
const {completionBlockerLabel, completionVersionNotice, completionStateLine, completionInspectionMatches, briefAuditLabel} = compiled.exports;
const clientModule = new Module(path.join(root, "app/tests/upgrade2-run-client.cjs"));
clientModule.filename = path.join(root, "app/tests/upgrade2-run-client.cjs");
clientModule.paths = [dependencies];
clientModule._compile(built.outputFiles.find(item => item.path.endsWith("/upgrade2-run-client.js")).text, clientModule.filename);
const {completionInspectionSchemaError} = clientModule.exports;
assert.equal(completionBlockerLabel("PROCESS_GROUP_EXIT_UNVERIFIED"), "进程组退出未核查");
assert.equal(completionBlockerLabel("UNKNOWN_BLOCK"), "UNKNOWN_BLOCK");
assert.equal(briefAuditLabel("MISSING_REQUIRED_CATEGORY"), "缺少必要类别");
assert.equal(briefAuditLabel("UNVERIFIED_CONTENT"), "内容未核查");
assert.equal(briefAuditLabel("未知状态"), "未知状态");
const historical = completionVersionNotice({stale: true, inspection_revision: 2, run_revision: 3, goal_revision: 1, current_goal_revision: 2});
assert.match(historical, /历史核查/);
assert.match(historical, /当前运行版本 3/);
assert.equal(completionVersionNotice({stale: false}), null);
const staleLine=completionStateLine({stale: true, completion_state: "BLOCKED"});
assert.match(staleLine, /历史核查记录/);
assert.ok(!staleLine.includes("完成状态"));
assert.equal(completionStateLine({stale: false, completion_state: "BLOCKED"}), "完成状态 BLOCKED");
const matchBase={run_id: "run-a", current_goal_revision: 2, finish_event_id: "finish-a"};
assert.equal(completionInspectionMatches(matchBase, "run-a", 2, "finish-a"), true);
assert.equal(completionInspectionMatches(matchBase, "run-b", 2, "finish-a"), false);
assert.equal(completionInspectionMatches(matchBase, "run-a", 3, "finish-a"), false);
assert.equal(completionInspectionMatches(matchBase, "run-a", 2, "finish-b"), false);
assert.notEqual(completionInspectionSchemaError({}), null);
const component = fs.readFileSync(path.join(root, "app/webui/Upgrade2CompletionInspection.tsx"), "utf8");
assert.ok(component.includes("PROCESS_GROUP_EXIT_UNVERIFIED"));
assert.ok(component.includes("completionInspectionSchemaError"));
const client = fs.readFileSync(path.join(root, "app/webui/upgrade2-run-client.ts"), "utf8");
assert.ok(client.includes("completionInspectionPath"));
assert.ok(client.includes("completionInspectionSchemaError"));
const run = fs.readFileSync(path.join(root, "app/webui/Upgrade2ConversationRun.tsx"), "utf8");
assert.ok(run.includes('["FAILED","SUCCEEDED"].includes(state.snapshot.status)'));
assert.ok(run.includes("<Upgrade2CompletionInspection"));
process.stdout.write(JSON.stringify({blocker_label: true, historical_notice: true, historical_state_hidden: true, finish_goal_run_match: true, invalid_schema_rejected: true, wiring: true}));
